#!/usr/bin/env python3
"""Exact certificate for an independent-fair-swap hierarchy obstruction.

The metric is the shortest-path metric of the unweighted 8-cycle.  Vertex 0
is the depot and vertices 1,...,7 are deterministic clients.  The posterior
optimum is therefore 8.  We enumerate all 11!! = 10395 unordered full binary
hierarchies on the clients and evaluate equations (11)--(13) using Fractions.

The minimum endpoint-coalescence value is 53/4, so its ratio to the posterior
optimum is 53/32 > 3/2 (and, in particular, > 29/20).  This does not refute
the desired 29/10 bound; it refutes attempts to make the independent-swap
hierarchy itself a 1.45- or 1.5-factor surrogate for the posterior tour.
"""

from __future__ import annotations

from fractions import Fraction
from functools import lru_cache


N = 8
CLIENTS = N - 1
FULL = (1 << CLIENTS) - 1
Tree = int | tuple["Tree", "Tree"]


def cycle_distance(i: int, j: int) -> int:
    gap = abs(i - j)
    return min(gap, N - gap)


@lru_cache(maxsize=None)
def hierarchies(mask: int) -> tuple[Tree, ...]:
    """Enumerate each unordered full binary hierarchy exactly once."""
    if mask & (mask - 1) == 0:
        return (mask.bit_length() - 1,)
    anchor = mask & -mask
    out: list[Tree] = []
    sub = (mask - 1) & mask
    while sub:
        other = mask ^ sub
        if sub & anchor and other:
            for left in hierarchies(sub):
                for right in hierarchies(other):
                    out.append((left, right))
        sub = (sub - 1) & mask
    return tuple(out)


def recurrence(tree: Tree) -> tuple[tuple[Fraction, ...], Fraction]:
    """Return the conditional endpoint law and internal open-path cost.

    All clients have probability one, so every nonempty block has occupancy
    one and equation (12) is simply the average of its child endpoint laws.
    """
    if isinstance(tree, int):
        nu = [Fraction(0)] * CLIENTS
        nu[tree] = Fraction(1)
        return tuple(nu), Fraction(0)
    nua, ella = recurrence(tree[0])
    nub, ellb = recurrence(tree[1])
    nu = tuple((a + b) / 2 for a, b in zip(nua, nub))
    cross = sum(
        nua[i] * nub[j] * cycle_distance(i + 1, j + 1)
        for i in range(CLIENTS)
        for j in range(CLIENTS)
    )
    return nu, ella + ellb + cross


def hierarchy_value(tree: Tree) -> Fraction:
    nu, internal = recurrence(tree)
    depot = 2 * sum(
        nu[i] * cycle_distance(0, i + 1) for i in range(CLIENTS)
    )
    return internal + depot


def orders(tree: Tree) -> tuple[tuple[int, ...], ...]:
    """All equally likely leaf orders generated by independent child swaps."""
    if isinstance(tree, int):
        return ((tree + 1,),)
    left, right = orders(tree[0]), orders(tree[1])
    out: list[tuple[int, ...]] = []
    for a in left:
        for b in right:
            out.extend((a + b, b + a))
    return tuple(out)


def direct_value(tree: Tree) -> Fraction:
    words = orders(tree)
    total = 0
    for word in words:
        total += cycle_distance(0, word[0])
        total += sum(cycle_distance(u, v) for u, v in zip(word, word[1:]))
        total += cycle_distance(word[-1], 0)
    return Fraction(total, len(words))


def main() -> None:
    hs = hierarchies(FULL)
    assert len(hs) == 10395

    best: Fraction | None = None
    minimizers = 0
    for tree in hs:
        via_recurrence = hierarchy_value(tree)
        via_orders = direct_value(tree)
        assert via_recurrence == via_orders
        if best is None or via_recurrence < best:
            best = via_recurrence
            minimizers = 1
        elif via_recurrence == best:
            minimizers += 1

    posterior = Fraction(N)
    assert best == Fraction(53, 4)
    ratio = best / posterior
    assert ratio == Fraction(53, 32)
    assert ratio > Fraction(3, 2)
    assert ratio > Fraction(29, 20)
    posterior_mst = Fraction(N - 1)
    parity_excess = posterior - posterior_mst
    assert parity_excess == 1
    parity_candidate = posterior + Fraction(19, 10) * parity_excess
    assert best - parity_candidate == Fraction(67, 20)

    print(f"hierarchies checked: {len(hs)}")
    print(f"minimizers: {minimizers}")
    print(f"posterior optimum: {posterior}")
    print(f"minimum hierarchy value: {best}")
    print(f"ratio: {ratio} = {float(ratio):.9f}")
    print(f"posterior TSP-minus-MST: {parity_excess}")
    print(f"excess over P + (19/10)(TSP-MST): {best - parity_candidate}")
    print("all exact checks passed")


if __name__ == "__main__":
    main()
